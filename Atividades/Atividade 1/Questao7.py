# QUESTÃO 7 - O DESCONTO DA LOJA

valor_original = float(input("Digite o valor total da compra: R$ "))

desconto = valor_original * 0.15
valor_final = valor_original - desconto

print("Valor original da compra: R$", valor_original)
print("Valor economizado (desconto): R$", desconto)
print("Valor final a pagar: R$", valor_final)
